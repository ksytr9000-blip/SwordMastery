using SwordMastery.Integrations;
using StardewValley;
using StardewValley.Monsters;
using StardewValley.Tools;
int passed=0;
void Check(bool ok,string name){if(!ok)throw new Exception(name);passed++;Console.WriteLine("PASS "+name);}
var api=new TowerApi();var helper=new StardewModdingAPI.Helper();helper.ModRegistry.Api=api;
var monitor=new StardewModdingAPI.Monitor();
var bridge=new TrialTowerCombat(helper,monitor,item=>item is MeleeWeapon&&ReferenceEquals(Game1.player.CurrentItem,item));
helper.Events.GameLoop.Raise();
var sword=new MeleeWeapon();Game1.player.CurrentItem=sword;
Check(api.Equipped!(Game1.player) is null,"ordinary sword swing is not claimed by the skill provider");
var attack=bridge.Begin(sword);
Check(attack?.Ready==true&&api.Begins==1&&api.Equipped!(Game1.player) is null,"skill owns only the capture scope");
Game1.player.CurrentItem=new Item();api.Stats["AttackDamage"]=900;
var target=new Monster();int native=0;
bool? hit=bridge.Hit(attack,target,100,false,1,value=>{native++;target.Health-=value;});
Check(hit==true&&native==1&&api.Raw==110&&Math.Abs(api.Basic-140)<1e-6,"skill raw avoids double equipment attack while proc basic and wing use launch snapshot");
Check(ReferenceEquals(api.Source,sword),"delayed skill retains original sword after equipment swap");
Check(Math.Abs(api.Chance-.03)<1e-6&&Math.Abs(api.Power-1.2)<1e-6,"ordinary skill preserves old critical baseline plus external bonuses");
bridge.Hit(attack,target,100,true,2,value=>target.Health-=value);
Check(api.Chance==1&&Math.Abs(api.Power-2.2)<1e-6,"guaranteed critical skill remains guaranteed without second native roll");
Check(bridge.Hit(null,target,100,false,1,_=>native++) is null&&native==1,"unarmed and ordinary damage request the original native path");
api.Accept=false;Game1.player.CurrentItem=sword;
var rejected=bridge.Begin(sword);
Check(bridge.Hit(rejected,target,100,false,1,_=>native++)==false&&native==1,"rejected skill cannot fall back to untracked Tower damage");
api.Accept=true;api.Stats["DirectDamageMultiplier"]=double.PositiveInfinity;
Check(bridge.Begin(sword)?.Ready==false,"nonfinite snapshot fails closed");
api.Throw=true;
Check(bridge.Hit(attack,target,100,false,1,_=>native++)==false&&native==2&&monitor.Warnings==1,"partial native failure has no retry");
Game1.currentLocation.NameOrUniqueName="Farm";
Check(bridge.Begin(sword) is null,"outside Tower keeps existing combat");
Console.WriteLine($"PASS: {passed} production sword Tower adapter checks; game/API stubbed.");
